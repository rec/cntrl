"""Generate the deterministic quarter-sine table used by MIDI LFOs."""

from decimal import ROUND_HALF_UP, Decimal, localcontext
from pathlib import Path

import tyro
from pydantic import BaseModel


class Table(BaseModel, frozen=True):
    output: Path = Path('firmware/include/cntrl/lfo_sine.h')


def generate(options: Table) -> None:
    values: list[int] = []
    with localcontext() as context:
        context.prec = 70
        pi = Decimal(
            '3.141592653589793238462643383279502884197169399375105820974944592307816'
        )
        for i in range(257):
            x = pi * i / 512
            term = total = x
            for j in range(1, 40):
                term *= -x * x / ((2 * j) * (2 * j + 1))
                total += term
            values.append(
                int((total * (1 << 31)).to_integral_value(rounding=ROUND_HALF_UP))
            )
    rows = [
        ', '.join(str(v) + 'u' for v in values[i : i + 8])
        for i in range(0, len(values), 8)
    ]
    options.output.write_text(
        '// Generated by scripts/generate_lfo_sine.py.\n'
        '#pragma once\n#include <cstdint>\n'
        'namespace cntrl::midi {\ninline constexpr uint32_t lfo_sine[] = {\n    '
        + ',\n    '.join(rows)
        + '\n};\n}\n'
    )


if __name__ == '__main__':
    generate(tyro.cli(Table))

"""Convert the vendored outline fonts to the display library's one-bit format."""

from pathlib import Path

import freetype
import tyro
from PIL import ImageFont
from pydantic import BaseModel

from .sparse_fonts import Outline


class Options(BaseModel, frozen=True):
    output: Path = Path(__file__).parent / 'firmware/patch_switcher'


class Bits:
    def __init__(self) -> None:
        self.data = bytearray()
        self.length = 0

    def append(self, value: int, width: int) -> None:
        for i in range(width - 1, -1, -1):
            if self.length % 8 == 0:
                self.data.append(0)
            self.data[-1] |= ((value >> i) & 1) << (7 - self.length % 8)
            self.length += 1


def bitmap_data(
    path: Path, size: int, outline: bool = False
) -> tuple[bytes, bytes, list[int]]:
    if outline:
        raster = Outline(path, autohint=True)
        glyphs = [
            raster.glyph(size, raster.face.get_char_index(c)) for c in range(32, 127)
        ]
        masks = [
            [
                int(
                    bool(g.pixels[y * ((g.width + 7) // 8) + x // 8] & (128 >> (x % 8)))
                )
                for y in range(g.height)
                for x in range(g.width)
            ]
            for g in glyphs
        ]
        cap = raster.glyph(size, raster.face.get_char_index(ord('H'))).top
        widths = [g.width for g in glyphs]
        heights = [g.height for g in glyphs]
        lefts = [g.left for g in glyphs]
        offsets = [g.top - g.height for g in glyphs]
        advances = []
        for c in range(32, 127):
            raster.face.load_char(
                chr(c),
                freetype.FT_LOAD_TARGET_MONO | freetype.FT_LOAD_FORCE_AUTOHINT,  # ty: ignore[unresolved-attribute]  # Public C extension API.
            )
            advances.append(round(raster.face.glyph.advance.x / 64))
    else:
        font = ImageFont.truetype(path, size, layout_engine=ImageFont.Layout.BASIC)
        cap = -font.getbbox('H', anchor='ls')[1]
        native = [font.getmask2(chr(c), mode='1', anchor='ls') for c in range(32, 127)]
        masks = [[m[i] for i in range(m.size[0] * m.size[1])] for m, _ in native]
        advances = [round(font.getlength(chr(c))) for c in range(32, 127)]
        widths = [m.size[0] for m, _ in native]
        heights = [m.size[1] for m, _ in native]
        lefts = [o[0] for _, o in native]
        offsets = [-o[1] - m.size[1] for m, o in native]
    fields = [widths, heights, lefts, offsets, advances]
    widths_bits = [
        max(1, max(v).bit_length())
        if i not in (2, 3)
        else next(
            b
            for b in range(1, 16)
            if min(v) >= -(1 << (b - 1)) and max(v) < 1 << (b - 1)
        )
        for i, v in enumerate(fields)
    ]
    data = bytearray()
    offsets_bytes = []
    for i, mask in enumerate(masks):
        offsets_bytes.append(len(data))
        bits = Bits()
        bits.append(0, 3)
        for v, b in zip(fields, widths_bits, strict=True):
            bits.append(v[i], b)
        for y in range(heights[i]):
            bits.append(0, 1)  # One uncompressed row.
            for x in range(widths[i]):
                bits.append(int(bool(mask[y * widths[i] + x])), 1)
        data.extend(bits.data)
    index_bits = max(1, max(offsets_bytes).bit_length())
    index = Bits()
    for o in offsets_bytes:
        index.append(o, index_bits)
    line = max(cap, max(cap - o for o in offsets))
    numbers = [
        int(n) for n in [1, 0, 32, 126, 0, 0, index_bits, *widths_bits, line, cap]
    ]
    return bytes(index.data), bytes(data), numbers


def bitmap_font(path: Path, name: str, size: int, outline: bool = False) -> str:
    index, data, numbers = bitmap_data(path, size, outline)
    symbol = f'{name}_{size}'
    arrays = ''
    for n, d in [('index', index), ('data', data)]:
        rows = [
            '    ' + ', '.join(f'0x{v:02x}' for v in d[i : i + 16]) + ','
            for i in range(0, len(d), 16)
        ]
        arrays += (
            f'static const unsigned char {symbol}_{n}[] CNTRL_FONT_FLASH = {{\n'
            + '\n'.join(rows)
            + '\n};\n'
        )
    return (
        arrays
        + f'const ILI9341_t3_font_t {symbol} CNTRL_FONT_FLASH = {{\n'
        + f'    {symbol}_index, 0, {symbol}_data,\n    '
        + ', '.join(str(v) for v in numbers)
        + '\n};\n'
    )


def generate(output: Path) -> None:
    root = Path(__file__).parents[3] / 'fonts'
    header = '#pragma once\n#include <ST7735_t3.h>\n'
    lookup = (
        'inline const ILI9341_t3_font_t *bitmap_font(unsigned face, unsigned size) {\n'
        '    switch (face) {\n'
    )
    for identifier, (name, source, license_note) in enumerate(
        [*FAMILIES, PAGE_FAMILY], 3
    ):
        text = (
            '// Generated by build_bitmap_fonts.py. Do not edit.\n// '
            + license_note
            + '\n'
        )
        text += (
            '#include "bitmap_fonts.h"\n#if defined(__IMXRT1062__)\n'
            '#define CNTRL_FONT_FLASH __attribute__((section(".progmem")))\n'
            '#else\n#define CNTRL_FONT_FLASH\n#endif\n'
        )
        lookup += f'    case {identifier}: switch (size) {{\n'
        for s in font_sizes(name):
            header += f'extern const ILI9341_t3_font_t {name}_{s};\n'
            text += bitmap_font(root / source, name, s, name == 'AtkinsonNextSemiBold')
            lookup += f'        case {s}: return &{name}_{s};\n'
        lookup += '        default: return nullptr;\n    }\n'
        (output / f'font_{name}.cpp').write_text(text)
    (output / 'bitmap_fonts.h').write_text(
        header + lookup + '    default: return nullptr;\n    }\n}\n'
    )


def font_sizes(name: str) -> list[int]:
    return (
        list(range(8, 33)) + [40, 48, 60, 72, 96]
        if name == 'AtkinsonNextSemiBold'
        else SIZES
    )


def main() -> None:
    generate(tyro.cli(Options).output)


